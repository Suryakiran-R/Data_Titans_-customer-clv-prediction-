import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
import seaborn as sns
import warnings
warnings.filterwarnings("ignore")

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

print("✅ Libraries imported")
FILE_PATH = "/content/drive/MyDrive/HCL_Data_Titans-20260314T075841Z-1-001/HCL_Data_Titans/Online Retail.xlsx"

df = pd.read_excel(FILE_PATH, engine="openpyxl")

# ── Standardise column names to avoid spacing issues ─────────────────────────
df.columns = df.columns.str.strip()
df.rename(columns={
    "Invoice"     : "InvoiceNo",
    "Price"       : "UnitPrice",
    "Customer ID" : "CustomerID"
}, inplace=True)

print(f"✅ Loaded: {df.shape[0]:,} rows × {df.shape[1]} columns")
print(f"Columns : {df.columns.tolist()}")
print(f"\n{df.head(3)}")


# ── CELL 3: Pre-Cleaning Snapshot ─────────────────────────────────────────────
print("\n" + "="*55)
print("PRE-CLEANING SNAPSHOT")
print("="*55)
print(f"Total rows             : {len(df):,}")
print(f"Unique customers       : {df['CustomerID'].nunique():,}")
print(f"Unique invoices        : {df['InvoiceNo'].nunique():,}")
print(f"Date range             : {df['InvoiceDate'].min()} → {df['InvoiceDate'].max()}")
print(f"\nMissing values:\n{df.isnull().sum()}")
print(f"\nNegative/zero UnitPrice: {(df['UnitPrice'] <= 0).sum():,}")
print(f"Negative/zero Quantity : {(df['Quantity'] <= 0).sum():,}")
print(f"Cancelled orders (C)   : {df['InvoiceNo'].astype(str).str.startswith('C').sum():,}")
print(f"Duplicate rows         : {df.duplicated().sum():,}")

# Track row counts at each step for a summary table at the end
audit = {"Raw": len(df)}


# ── CELL 4: STEP 1 — Drop missing CustomerID ──────────────────────────────────
df = df.dropna(subset=["CustomerID"])
df["CustomerID"] = df["CustomerID"].astype(int)
audit["After drop NaN CustomerID"] = len(df)
print(f"\n✅ Step 1 | Dropped missing CustomerID → {len(df):,} rows remain "
      f"({audit['Raw'] - len(df):,} removed)")


# ── CELL 5: STEP 2 — Remove cancelled orders ──────────────────────────────────
df = df[~df["InvoiceNo"].astype(str).str.startswith("C")].copy()
audit["After remove cancellations"] = len(df)
print(f"✅ Step 2 | Removed cancelled orders   → {len(df):,} rows remain")


# ── CELL 6: STEP 3 — Remove UnitPrice ≤ 0 and Quantity ≤ 0 ───────────────────
df = df[(df["UnitPrice"] > 0) & (df["Quantity"] > 0)].copy()
audit["After remove bad price/qty"] = len(df)
print(f"✅ Step 3 | Removed bad price/quantity → {len(df):,} rows remain")


# ── CELL 7: STEP 4 — Drop duplicates ──────────────────────────────────────────
df = df.drop_duplicates().copy()
audit["After drop duplicates"] = len(df)
print(f"✅ Step 4 | Dropped duplicates         → {len(df):,} rows remain")


# ── CELL 8: EXTRA CLEANING ────────────────────────────────────────────────────

# 8a. Parse InvoiceDate properly
df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"])

# 8b. Compute TotalPrice (line-item revenue)
df["TotalPrice"] = df["Quantity"] * df["UnitPrice"]

# 8c. Remove extreme outlier unit prices (above 99.9th percentile)
#     These are almost always data entry errors, not real transactions
price_cap = df["UnitPrice"].quantile(0.999)
qty_cap   = df["Quantity"].quantile(0.999)
before = len(df)
df = df[(df["UnitPrice"] <= price_cap) & (df["Quantity"] <= qty_cap)].copy()
audit["After outlier cap"] = len(df)
print(f"✅ Extra  | Capped outliers "
      f"(Price>{price_cap:.0f} or Qty>{qty_cap:.0f}) → {before - len(df):,} removed")

# 8d. Remove known non-product StockCodes (postage, fees, samples)
bad_codes = {"POST", "DOT", "M", "BANK CHARGES", "PADS", "C2",
             "AMAZONFEE", "S", "CRUK", "D", "B"}
before = len(df)
df = df[~df["StockCode"].astype(str).str.upper().isin(bad_codes)].copy()
audit["After remove bad StockCodes"] = len(df)
print(f"✅ Extra  | Removed service StockCodes → {before - len(df):,} removed")

# 8e. Standardise text columns
df["Description"] = df["Description"].astype(str).str.strip().str.title()
df["Country"]     = df["Country"].astype(str).str.strip()

# 8f. Remove countries that appear suspiciously rarely (< 5 customers)
country_customer_counts = df.groupby("Country")["CustomerID"].nunique()
valid_countries = country_customer_counts[country_customer_counts >= 5].index
before = len(df)
df = df[df["Country"].isin(valid_countries)].copy()
audit["After rare country filter"] = len(df)
print(f"✅ Extra  | Removed rare countries     → {before - len(df):,} removed")

print(f"\n📊 Clean transaction table: {len(df):,} rows")


# ── CELL 9: STEP 9 — is_UK_customer flag ──────────────────────────────────────
df["is_UK_customer"] = (df["Country"] == "United Kingdom").astype(int)
print(f"\n✅ Step 9 | UK transactions     : {df['is_UK_customer'].sum():,}")
print(f"           Non-UK transactions : {(df['is_UK_customer']==0).sum():,}")


# ── CELL 10: STEP 8 — Seasonality features ────────────────────────────────────
df["Month"]     = df["InvoiceDate"].dt.month
df["Quarter"]   = df["InvoiceDate"].dt.quarter
df["DayOfWeek"] = df["InvoiceDate"].dt.dayofweek   # 0=Mon, 6=Sun
df["IsWeekend"] = (df["DayOfWeek"] >= 5).astype(int)
df["IsQ4"]      = (df["Quarter"] == 4).astype(int)
df["Year"]      = df["InvoiceDate"].dt.year

# Cyclic month encoding — so Dec and Jan are numerically close
df["Month_sin"] = np.sin(2 * np.pi * df["Month"] / 12)
df["Month_cos"] = np.cos(2 * np.pi * df["Month"] / 12)

print(f"✅ Step 8 | Seasonality features added: "
      f"Month, Quarter, DayOfWeek, IsWeekend, IsQ4, Month_sin, Month_cos")


# ── CELL 11: Define Cutoff — Past vs Future window ────────────────────────────
max_date    = df["InvoiceDate"].max()
cutoff_date = max_date - pd.Timedelta(days=30)
snapshot    = cutoff_date   # reference for recency

print(f"\n📅 Max date in dataset : {max_date.date()}")
print(f"📅 Cutoff date         : {cutoff_date.date()}")
print(f"   Observation window : everything BEFORE {cutoff_date.date()}")
print(f"   Target window      : {cutoff_date.date()} → {max_date.date()}")

df_past   = df[df["InvoiceDate"] <  cutoff_date].copy()
df_future = df[df["InvoiceDate"] >= cutoff_date].copy()

print(f"\n   Past rows   : {len(df_past):,}")
print(f"   Future rows : {len(df_future):,}")


# ── CELL 12: Build Customer-Level Feature Table ───────────────────────────────

# Recency — days since last purchase before cutoff
recency_df = (
    df_past.groupby("CustomerID")["InvoiceDate"].max().reset_index()
    .rename(columns={"InvoiceDate": "LastPurchaseDate"})
)
recency_df["Recency_days"] = (snapshot - recency_df["LastPurchaseDate"]).dt.days

# Frequency — unique invoice count
freq_df = (
    df_past.groupby("CustomerID")["InvoiceNo"].nunique().reset_index()
    .rename(columns={"InvoiceNo": "Frequency"})
)

# Monetary — total spend
monetary_df = (
    df_past.groupby("CustomerID")["TotalPrice"].sum().reset_index()
    .rename(columns={"TotalPrice": "MonetaryTotal"})
)

# Average order value
aov_df = (
    df_past.groupby("CustomerID")["TotalPrice"].mean().reset_index()
    .rename(columns={"TotalPrice": "AvgOrderValue"})
)

# Unique products purchased
products_df = (
    df_past.groupby("CustomerID")["StockCode"].nunique().reset_index()
    .rename(columns={"StockCode": "UniqueProducts"})
)

# Customer tenure (days between first and last purchase)
tenure_df = (
    df_past.groupby("CustomerID")["InvoiceDate"].min().reset_index()
    .rename(columns={"InvoiceDate": "FirstPurchaseDate"})
)
tenure_df["CustomerTenure_days"] = (snapshot - tenure_df["FirstPurchaseDate"]).dt.days

# Average inter-purchase gap
def avg_gap(group):
    dates = group.sort_values().unique()
    if len(dates) < 2:
        return np.nan
    return pd.Series(dates).diff().dt.days.dropna().mean()

gap_df = (
    df_past.groupby("CustomerID")["InvoiceDate"].apply(avg_gap).reset_index()
    .rename(columns={"InvoiceDate": "AvgDaysBetweenOrders"})
)

# % of purchases in Q4 (Christmas season — very relevant for retail)
q4_df = (
    df_past.groupby("CustomerID")["IsQ4"].mean().reset_index()
    .rename(columns={"IsQ4": "PctQ4Purchases"})
)

# % purchases on weekends
wknd_df = (
    df_past.groupby("CustomerID")["IsWeekend"].mean().reset_index()
    .rename(columns={"IsWeekend": "PctWeekendPurchases"})
)

# is_UK_customer flag
uk_df = (
    df_past.groupby("CustomerID")["is_UK_customer"].max().reset_index()
)

# Spend standard deviation (measures volatility — irregular vs consistent buyer)
std_df = (
    df_past.groupby("CustomerID")["TotalPrice"].std().reset_index()
    .rename(columns={"TotalPrice": "SpendStdDev"})
)

# Most frequent country per customer
country_mode_df = (
    df_past.groupby("CustomerID")["Country"]
    .agg(lambda x: x.mode()[0]).reset_index()
    .rename(columns={"Country": "PrimaryCountry"})
)

# ── Merge all features ────────────────────────────────────────────────────────
cust = recency_df[["CustomerID", "Recency_days"]].copy()
for frame in [freq_df, monetary_df, aov_df, products_df,
              tenure_df[["CustomerID", "CustomerTenure_days"]],
              gap_df, q4_df, wknd_df, uk_df, std_df, country_mode_df]:
    cust = cust.merge(frame, on="CustomerID", how="left")

# Fill single-purchase customers gap with their recency
cust["AvgDaysBetweenOrders"] = cust["AvgDaysBetweenOrders"].fillna(cust["Recency_days"])
# Fill zero-variance customers (only 1 purchase) std with 0
cust["SpendStdDev"] = cust["SpendStdDev"].fillna(0)

print(f"\n✅ Customer feature table: {len(cust):,} customers × {cust.shape[1]-1} features")


# ── CELL 13: Target Variable — future_spend_30d ───────────────────────────────
target_df = (
    df_future.groupby("CustomerID")["TotalPrice"].sum().reset_index()
    .rename(columns={"TotalPrice": "future_spend_30d"})
)

cust = cust.merge(target_df, on="CustomerID", how="left")
cust["future_spend_30d"] = cust["future_spend_30d"].fillna(0)

print(f"\n✅ Target variable added")
print(cust["future_spend_30d"].describe().round(2))
print(f"\nCustomers with £0 future spend  : {(cust['future_spend_30d']==0).sum():,}")
print(f"Customers with +ve future spend : {(cust['future_spend_30d']>0).sum():,}")


# ── CELL 14: STEP 7 — Churn flag ──────────────────────────────────────────────
cust["is_churned"] = (cust["future_spend_30d"] == 0).astype(int)
print(f"\n✅ Step 7 | Churn rate in 30-day window: {cust['is_churned'].mean()*100:.1f}%")


# ── CELL 15: STEP 5 — log1p on target ─────────────────────────────────────────
cust["future_spend_30d_log"] = np.log1p(cust["future_spend_30d"])
print(f"✅ Step 5 | log1p target created: future_spend_30d_log")


# ── CELL 16: RFM Scores (1–5) ─────────────────────────────────────────────────
def quantile_score(series, ascending=True):
    labels = [5,4,3,2,1] if ascending else [1,2,3,4,5]
    return pd.qcut(series.rank(method="first"), q=5, labels=labels).astype(int)

cust["R_score"] = quantile_score(cust["Recency_days"],  ascending=True)
cust["F_score"] = quantile_score(cust["Frequency"],     ascending=False)
cust["M_score"] = quantile_score(cust["MonetaryTotal"], ascending=False)
cust["RFM_score"] = cust["R_score"] + cust["F_score"] + cust["M_score"]

print(f"✅ RFM scores (R/F/M 1–5) added")


# ── CELL 17: STEP 6 — K-Means Customer Segmentation ──────────────────────────
rfm_cols   = ["Recency_days", "Frequency", "MonetaryTotal"]
rfm_matrix = cust[rfm_cols].copy()

scaler     = StandardScaler()
rfm_scaled = scaler.fit_transform(rfm_matrix)

# Find best K via silhouette score
print("\nFinding optimal K...")
sil_scores = {}
for k in range(2, 8):
    km  = KMeans(n_clusters=k, random_state=42, n_init=10)
    lbl = km.fit_predict(rfm_scaled)
    sil_scores[k] = silhouette_score(rfm_scaled, lbl)
    print(f"  K={k}  silhouette={sil_scores[k]:.4f}")

best_k = max(sil_scores, key=sil_scores.get)
print(f"\n  ➡ Best K = {best_k}")

kmeans = KMeans(n_clusters=best_k, random_state=42, n_init=10)
cust["Cluster"] = kmeans.fit_predict(rfm_scaled)

# Label clusters by monetary rank
cluster_means = cust.groupby("Cluster")["MonetaryTotal"].mean()
rank_map      = cluster_means.rank(ascending=False).astype(int)
segment_names = {1:"Champions", 2:"Loyal Customers",
                 3:"At Risk", 4:"Hibernating", 5:"Lost", 6:"New Customers"}
cust["Segment"] = cust["Cluster"].map(rank_map).map(segment_names).fillna("Other")

print(f"\n✅ Step 6 | Segmentation complete")
print(cust.groupby("Segment")[["Recency_days","Frequency","MonetaryTotal"]].mean().round(1))


# ── CELL 18: PLOTS ────────────────────────────────────────────────────────────
fig = plt.figure(figsize=(18, 14))
gs  = gridspec.GridSpec(3, 3, figure=fig, hspace=0.45, wspace=0.35)
palette = ["#378ADD","#1D9E75","#EF9F27","#D4537E","#7F77DD","#D85A30"]

# 1. Raw target distribution
ax1 = fig.add_subplot(gs[0, 0])
ax1.hist(cust["future_spend_30d"].clip(upper=cust["future_spend_30d"].quantile(0.95)),
         bins=40, color="#378ADD", edgecolor="white", linewidth=0.5)
ax1.set_title("Target: raw spend (skewed)", fontsize=11)
ax1.set_xlabel("future_spend_30d (£)")

# 2. Log-transformed target
ax2 = fig.add_subplot(gs[0, 1])
ax2.hist(cust["future_spend_30d_log"], bins=40, color="#1D9E75", edgecolor="white", linewidth=0.5)
ax2.set_title("Target: log1p(spend) — normalised", fontsize=11)
ax2.set_xlabel("log1p(future_spend_30d)")

# 3. Churn breakdown
ax3 = fig.add_subplot(gs[0, 2])
churn_counts = cust["is_churned"].value_counts()
ax3.bar(["Active (will buy)", "Churned (£0 spend)"],
        [churn_counts.get(0,0), churn_counts.get(1,0)],
        color=["#1D9E75","#E24B4A"], edgecolor="white")
ax3.set_title("30-day churn split", fontsize=11)

# 4. Recency distribution
ax4 = fig.add_subplot(gs[1, 0])
ax4.hist(cust["Recency_days"], bins=40, color="#7F77DD", edgecolor="white", linewidth=0.5)
ax4.set_title("Recency distribution (days)", fontsize=11)
ax4.set_xlabel("Days since last purchase")

# 5. Frequency distribution (capped)
ax5 = fig.add_subplot(gs[1, 1])
ax5.hist(cust["Frequency"].clip(upper=50), bins=40, color="#EF9F27", edgecolor="white", linewidth=0.5)
ax5.set_title("Frequency (invoice count)", fontsize=11)
ax5.set_xlabel("Number of orders (capped at 50)")

# 6. Customer segments bar
ax6 = fig.add_subplot(gs[1, 2])
seg_counts = cust["Segment"].value_counts()
bars = ax6.bar(seg_counts.index, seg_counts.values,
               color=palette[:len(seg_counts)], edgecolor="white")
ax6.set_title("Customers per segment", fontsize=11)
ax6.tick_params(axis="x", rotation=30)
for bar, val in zip(bars, seg_counts.values):
    ax6.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 5,
             str(val), ha="center", fontsize=8)

# 7. Cluster scatter: Recency vs Spend
ax7 = fig.add_subplot(gs[2, 0:2])
for i, seg in enumerate(cust["Segment"].unique()):
    mask = cust["Segment"] == seg
    ax7.scatter(cust.loc[mask,"Recency_days"],
                cust.loc[mask,"MonetaryTotal"].clip(upper=cust["MonetaryTotal"].quantile(0.95)),
                label=seg, alpha=0.45, s=12, color=palette[i % len(palette)])
ax7.set_xlabel("Recency (days)")
ax7.set_ylabel("Total Spend (£)")
ax7.set_title("Customer segments: Recency vs Total Spend", fontsize=11)
ax7.legend(fontsize=8, markerscale=2)

# 8. Monthly transaction volume
ax8 = fig.add_subplot(gs[2, 2])
monthly = df.groupby(df["InvoiceDate"].dt.to_period("M")).size()
ax8.plot(monthly.index.astype(str), monthly.values, color="#378ADD", linewidth=1.5, marker="o", markersize=3)
ax8.set_title("Monthly transaction volume", fontsize=11)
ax8.tick_params(axis="x", rotation=45)
ax8.set_xlabel("")

plt.suptitle("CLV Project — Data Cleaning & EDA Summary", fontsize=14, fontweight="bold", y=1.01)
plt.savefig("clv_eda_summary.png", dpi=150, bbox_inches="tight")
plt.close()
print("✅ Plot saved: clv_eda_summary.png")


# ── CELL 19: Audit Trail ──────────────────────────────────────────────────────
audit["Final clean rows"] = len(df)
print("\n" + "="*55)
print("ROW COUNT AUDIT TRAIL")
print("="*55)
prev = None
for step, count in audit.items():
    if prev is not None:
        removed = prev - count
        pct     = removed / list(audit.values())[0] * 100
        print(f"  {step:<35} {count:>8,}  (−{removed:,} | {pct:.1f}%)")
    else:
        print(f"  {step:<35} {count:>8,}")
    prev = count


# ── CELL 20: Define X / y for Modelling ───────────────────────────────────────
DROP = ["CustomerID","LastPurchaseDate","FirstPurchaseDate",
        "PrimaryCountry","Segment","Cluster",
        "future_spend_30d","future_spend_30d_log","is_churned"]

feature_cols = [c for c in cust.columns if c not in DROP]
X       = cust[feature_cols]
y_raw   = cust["future_spend_30d"]       # for evaluation (real £ values)
y_log   = cust["future_spend_30d_log"]   # for training (log scale)
y_churn = cust["is_churned"]             # Stage-1 classifier target

print(f"\n✅ Modelling inputs ready")
print(f"   X shape  : {X.shape}")
print(f"   Features : {feature_cols}")
print(f"\n{'='*55}")
print("PREPROCESSING COMPLETE — hand off to model training")
print("="*55)


